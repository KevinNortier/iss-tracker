"""
Generates reference values for the orbit unit tests.

The values come from independent, well-established implementations:
  * python-sgp4  (a wrapper around David Vallado's reference SGP4 code)
  * Skyfield     (look angles, sun position and Earth shadow)

Usage (run from any scratch directory outside the project):
    python -m venv venv
    venv/Scripts/pip install sgp4 skyfield       # Windows
    venv/Scripts/python <project>/tools/generate_orbit_reference.py

Writes app/src/test/java/io/github/kevinnortier/isstracker/orbit/ReferenceData.kt
Skyfield downloads the JPL ephemeris de421.bsp (~17 MB) into the current directory
the first time it runs, so don't run it from inside the project.
"""

from pathlib import Path

import sgp4
import skyfield
from sgp4.api import Satrec
from skyfield.api import EarthSatellite, load, wgs84


def checksum(line: str) -> str:
    """Replace the last character of a TLE line with a correct checksum."""
    total = 0
    for ch in line[:68]:
        if ch.isdigit():
            total += int(ch)
        elif ch == "-":
            total += 1
    return line[:68] + str(total % 10)


# Near-earth test cases from Vallado's SGP4 verification set, a recent ISS TLE,
# and a synthetic very-low-perigee case to exercise the perigee < 98 km branch.
TLES = {
    "VANGUARD_00005": (
        "1 00005U 58002B   00179.78495062  .00000023  00000-0  28098-4 0  4753",
        "2 00005  34.2682 348.7242 1859667 331.7664  19.3264 10.82419157413667",
    ),
    "SAT_06251": (
        "1 06251U 62025E   06176.82412014  .00008885  00000-0  12808-3 0  3985",
        "2 06251  58.0579  54.0425 0030035 139.1568 221.1854 15.56387291  6774",
    ),
    "SAT_28057": (
        "1 28057U 03049A   06177.78615833  .00000060  00000-0  35940-4 0  1836",
        "2 28057  98.4283 247.6961 0000884  88.1964 271.9322 14.35478080140550",
    ),
    "STR3_88888": (
        "1 88888U          80275.98708465  .00073094  13844-3  66816-4 0    87",
        "2 88888  72.8435 115.9689 0086731  52.6988 110.5714 16.05824518  1058",
    ),
    "ISS_25544": (
        "1 25544U 98067A   26325.59122794  .00010184  00000+0  18913-3 0  9995",
        "2 25544  51.6319 241.1476 0007381  50.6945 309.4697 15.49534382596158",
    ),
    # perigee ~60 km  (perige < 98 km branch)
    "LOW_PERIGEE_99999": (
        "1 99999U 00000A   26325.50000000  .00010000  00000-0  10000-3 0  9990",
        "2 99999  51.6000 200.0000 0650000  90.0000 270.0000 15.20000000    10",
    ),
    # perigee ~125 km (98 km < perige < 156 km branch)
    "LOW_PERIGEE_99998": (
        "1 99998U 00000A   26325.50000000  .00010000  00000-0  10000-3 0  9990",
        "2 99998  51.6000 200.0000 0550000  90.0000 270.0000 15.20000000    10",
    ),
}
TLES = {k: (checksum(l1), checksum(l2)) for k, (l1, l2) in TLES.items()}

OBSERVERS = {
    # Public, well-known places (never a personal location).
    "GREENWICH": (51.4769, -0.0005, 46.0),
    "SYDNEY": (-33.8568, 151.2153, 5.0),
}


def kt_double(x: float) -> str:
    return repr(float(x))


def main() -> None:
    out = []
    out.append("package io.github.kevinnortier.isstracker.orbit")
    out.append("")
    out.append("// GENERATED by tools/generate_orbit_reference.py - do not edit by hand.")
    out.append(f"// python-sgp4 {sgp4.__version__}, Skyfield {skyfield.__version__}")
    out.append("")
    out.append("@Suppress(\"LargeClass\")")
    out.append("internal object ReferenceData {")
    out.append("")
    out.append("    class TleCase(")
    out.append("        val name: String,")
    out.append("        val line1: String,")
    out.append("        val line2: String,")
    out.append("        val epochJulianDate: Double,")
    out.append("        val states: List<State>,")
    out.append("    )")
    out.append("")
    out.append("    /** minutes since epoch, TEME position (km), TEME velocity (km/s) */")
    out.append("    class State(val tsince: Double, val r: DoubleArray, val v: DoubleArray)")
    out.append("")
    out.append("    class LookCase(")
    out.append("        val tle: String,")
    out.append("        val latitudeDeg: Double,")
    out.append("        val longitudeDeg: Double,")
    out.append("        val altitudeMeters: Double,")
    out.append("        val samples: List<LookSample>,")
    out.append("    )")
    out.append("")
    out.append("    /** epochMillis (UTC), azimuth (deg), elevation (deg), range (km), range rate (km/s), sunlit */")
    out.append("    class LookSample(")
    out.append("        val epochMillis: Long,")
    out.append("        val azimuthDeg: Double,")
    out.append("        val elevationDeg: Double,")
    out.append("        val rangeKm: Double,")
    out.append("        val rangeRateKmPerSec: Double,")
    out.append("        val sunlit: Boolean,")
    out.append("    )")
    out.append("")
    out.append("    class PassCase(")
    out.append("        val tle: String,")
    out.append("        val latitudeDeg: Double,")
    out.append("        val longitudeDeg: Double,")
    out.append("        val altitudeMeters: Double,")
    out.append("        val minElevationDeg: Double,")
    out.append("        val fromMillis: Long,")
    out.append("        val untilMillis: Long,")
    out.append("        val passes: List<PassRef>,")
    out.append("    )")
    out.append("")
    out.append("    /** rise/apex/set epochMillis (UTC), apex elevation (deg), rise/set azimuth (deg), visible to the eye */")
    out.append("    class PassRef(")
    out.append("        val riseMillis: Long,")
    out.append("        val apexMillis: Long,")
    out.append("        val setMillis: Long,")
    out.append("        val apexElevationDeg: Double,")
    out.append("        val riseAzimuthDeg: Double,")
    out.append("        val setAzimuthDeg: Double,")
    out.append("        val visible: Boolean,")
    out.append("    )")
    out.append("")
    out.append("    /** epochMillis (UTC), sun azimuth (deg), sun elevation (deg) */")
    out.append("    class SunSample(val epochMillis: Long, val azimuthDeg: Double, val elevationDeg: Double)")
    out.append("")

    # --- SGP4 propagation -----------------------------------------------------
    out.append("    val tleCases: List<TleCase> = listOf(")
    for name, (l1, l2) in TLES.items():
        sat = Satrec.twoline2rv(l1, l2)
        out.append("        TleCase(")
        out.append(f"            name = \"{name}\",")
        out.append(f"            line1 = \"{l1}\",")
        out.append(f"            line2 = \"{l2}\",")
        out.append(f"            epochJulianDate = {kt_double(sat.jdsatepoch + sat.jdsatepochF)},")
        out.append("            states = listOf(")
        for tsince in range(0, 1441, 120):
            e, r, v = sat.sgp4_tsince(float(tsince))
            if e != 0:
                break
            out.append(
                f"                State({kt_double(tsince)}, "
                f"doubleArrayOf({', '.join(kt_double(c) for c in r)}), "
                f"doubleArrayOf({', '.join(kt_double(c) for c in v)})),"
            )
        out.append("            ),")
        out.append("        ),")
    out.append("    )")
    out.append("")

    # --- Look angles + sunlit (Skyfield) -----------------------------------------
    ts = load.timescale(builtin=True)
    eph = load("de421.bsp")
    earth, sun = eph["earth"], eph["sun"]

    l1, l2 = TLES["ISS_25544"]
    iss = EarthSatellite(l1, l2, "ISS", ts)
    epoch_unix = (iss.epoch.tt - 2440587.5) * 86400.0  # rough, only used to pick sample times
    start_ms = int(round(epoch_unix / 60.0)) * 60_000 - 12 * 3_600_000

    out.append("    val lookCases: List<LookCase> = listOf(")
    for obs_name, (lat, lon, alt) in OBSERVERS.items():
        topos = wgs84.latlon(lat, lon, elevation_m=alt)
        out.append("        LookCase(")
        out.append("            tle = \"ISS_25544\",")
        out.append(f"            latitudeDeg = {kt_double(lat)},")
        out.append(f"            longitudeDeg = {kt_double(lon)},")
        out.append(f"            altitudeMeters = {kt_double(alt)},")
        out.append("            samples = listOf(")
        for i in range(0, 24 * 60, 37):  # every 37 min over a day
            ms = start_ms + i * 60_000
            t = ts.from_datetime(_utc(ms))
            diff = iss - topos
            alt_a, az_a, dist = diff.at(t).altaz()
            # Range rate by central difference (0.5 s each side).
            t_minus = ts.from_datetime(_utc(ms - 500))
            t_plus = ts.from_datetime(_utc(ms + 500))
            rr = diff.at(t_plus).distance().km - diff.at(t_minus).distance().km
            sunlit = bool(iss.at(t).is_sunlit(eph))
            out.append(
                f"                LookSample({ms}L, {kt_double(az_a.degrees)}, {kt_double(alt_a.degrees)}, "
                f"{kt_double(dist.km)}, {kt_double(rr)}, {str(sunlit).lower()}),"
            )
        out.append("            ),")
        out.append("        ),")
    out.append("    )")
    out.append("")

    # --- Passes (Skyfield find_events) --------------------------------------------
    out.append("    val passCases: List<PassCase> = listOf(")
    for obs_name, (lat, lon, alt) in OBSERVERS.items():
        topos = wgs84.latlon(lat, lon, elevation_m=alt)
        observer_at = earth + topos
        for min_el in (0.0, 10.0):
            from_ms = start_ms
            until_ms = start_ms + 3 * 86_400_000
            t0 = ts.from_datetime(_utc(from_ms))
            t1 = ts.from_datetime(_utc(until_ms))
            times, events = iss.find_events(topos, t0, t1, altitude_degrees=min_el)
            out.append("        PassCase(")
            out.append("            tle = \"ISS_25544\",")
            out.append(f"            latitudeDeg = {kt_double(lat)},")
            out.append(f"            longitudeDeg = {kt_double(lon)},")
            out.append(f"            altitudeMeters = {kt_double(alt)},")
            out.append(f"            minElevationDeg = {kt_double(min_el)},")
            out.append(f"            fromMillis = {from_ms}L,")
            out.append(f"            untilMillis = {until_ms}L,")
            out.append("            passes = listOf(")
            i = 0
            evs = list(zip(times, events))
            while i + 2 < len(evs) + 0:
                (tr, er), (tc, ec), (tset, es) = evs[i], evs[i + 1], evs[i + 2]
                if (er, ec, es) != (0, 1, 2):
                    i += 1
                    continue
                diff = iss - topos
                apex_alt, _, _ = diff.at(tc).altaz()
                _, rise_az, _ = diff.at(tr).altaz()
                _, set_az, _ = diff.at(tset).altaz()
                # Visible: some 10 s sample with ISS above max(min_el, 0), sunlit, and sun below -6 deg.
                visible = False
                rise_ms = _ms(tr)
                set_ms = _ms(tset)
                for ms in range(rise_ms, set_ms + 1, 10_000):
                    t = ts.from_datetime(_utc(ms))
                    a, _, _ = diff.at(t).altaz()
                    if a.degrees < max(min_el, 0.0):
                        continue
                    sun_alt, _, _ = observer_at.at(t).observe(sun).apparent().altaz()
                    if sun_alt.degrees < -6.0 and iss.at(t).is_sunlit(eph):
                        visible = True
                        break
                out.append(
                    f"                PassRef({rise_ms}L, {_ms(tc)}L, {set_ms}L, {kt_double(apex_alt.degrees)}, "
                    f"{kt_double(rise_az.degrees)}, {kt_double(set_az.degrees)}, {str(visible).lower()}),"
                )
                i += 3
            out.append("            ),")
            out.append("        ),")
    out.append("    )")
    out.append("")

    # --- Sun position ------------------------------------------------------------
    lat, lon, alt = OBSERVERS["GREENWICH"]
    observer = earth + wgs84.latlon(lat, lon, elevation_m=alt)
    out.append(f"    val sunObserverLatitudeDeg = {kt_double(lat)}")
    out.append(f"    val sunObserverLongitudeDeg = {kt_double(lon)}")
    out.append(f"    val sunObserverAltitudeMeters = {kt_double(alt)}")
    out.append("    val sunSamples: List<SunSample> = listOf(")
    base_ms = 1_767_225_600_000  # 2026-01-01T00:00:00Z
    for i in range(0, 365 * 24, 53):  # every 53 hours over a year
        ms = base_ms + i * 3_600_000
        t = ts.from_datetime(_utc(ms))
        alt_a, az_a, _ = observer.at(t).observe(sun).apparent().altaz()
        out.append(f"        SunSample({ms}L, {kt_double(az_a.degrees)}, {kt_double(alt_a.degrees)}),")
    out.append("    )")
    out.append("}")
    out.append("")

    project_root = Path(__file__).resolve().parent.parent
    target = project_root / "app/src/test/java/io/github/kevinnortier/isstracker/orbit/ReferenceData.kt"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(out), encoding="utf-8")
    print(f"Wrote {target}")


def _ms(t) -> int:
    """Skyfield Time -> epoch milliseconds (UTC)."""
    return int(round(t.utc_datetime().timestamp() * 1000.0))


def _utc(ms: int):
    from datetime import datetime, timezone

    return datetime.fromtimestamp(ms / 1000.0, tz=timezone.utc)


if __name__ == "__main__":
    main()
